export type RunEvidenceLifecycleHooks = {
  manifestLocked?: (run: EvalRun) => void | Promise<void>;
  executionSealed?: (run: EvalRun) => void | Promise<void>;
  executionPlanned?: (run: EvalRun) => void | Promise<void>;
};

